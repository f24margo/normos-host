"""
Демо-модуль ассистента без внешних зависимостей.
"""

def ask_gemini(prompt: str, user=None) -> str:
    """
    Автономная заглушка для демо-показа.
    Не требует подключения к API и сторонних библиотек.
    """
    p = prompt.lower()
    
    if "триз" in p or "коліз" in p:
        return (
            "<strong>[ТРИЗ-Аналіз]:</strong> Метод передбачає виявлення оперативного часу "
            "та простору суперечності. Наприклад, якщо регламент зобов'язує прийняти рішення "
            "протягом 3 днів, а Закон вимагає 10 днів на обговорення, ТРИЗ пропонує поділ за "
            "умовами або введення проміжного протокольного рішення."
        )
    
    if "інструкці" in p or "завантажи" in p:
        return (
            "<strong>[Довідка]:</strong> Перейдіть у розділ <strong>'⚡ Швидка перевірка'</strong>, "
            "натисніть на рамку вибору файла (.txt/.docx). Текст автоматично завантажиться у поле, "
            "після чого натисніть кнопку 'Запустити перевірку'."
        )
        
    if "про" in p or "тариф" in p or "передплат" in p:
        return (
            "<strong>[Платний доступ]:</strong> Розширений ТРИЗ-модуль та генерація юридичних "
            "висновків будуть доступні у плані Enterprise. Доступ оформлюється через адміністратора системи."
        )

    return (
        "Модуль ТРИЗ знаходиться у стадії розробки. В майбутній версії тут буде доступний "
        "автоматичний підбір альтернативних юридичних формулювань для усунення колізій."
    )